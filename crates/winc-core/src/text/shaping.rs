//! 需要整形的文字：字形取决于前后字符的文字。
//!
//! 组合符号、连写和字形重排使这类字符无法逐个绘制和测宽；绘制时交给渲染层按字形簇或整段整形。

/// 是否需要整形才能正确显示 `c`：组合符号，以及字形随上下文变化的文字。
///
/// 包括阿拉伯文、希伯来文、印度诸文字、泰文、老挝文、藏文、缅甸文、高棉文、蒙古文和谚文字母，
/// 按 Unicode 区块判断；区块中不需要整形的字符一并整形，结果相同，只多一次整形。
pub fn needs_shaping(c: char) -> bool {
    matches!(c as u32,
        0x0300..=0x036F
        | 0x0590..=0x1CFF
        | 0x1DC0..=0x1DFF
        | 0x20D0..=0x20FF
        | 0xA800..=0xABFF
        | 0xFB1D..=0xFDFF
        | 0xFE20..=0xFE2F
        | 0xFE70..=0xFEFF
        | 0x10800..=0x11FFF)
}

